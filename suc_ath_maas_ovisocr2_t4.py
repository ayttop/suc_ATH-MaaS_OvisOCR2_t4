BBOX_PATTERN = re.compile(
    r'<img\s+src=["\']images/bbox_'
    r'(\d+)_(\d+)_(\d+)_(\d+)\.jpg["\']\s*/?>',
    flags=re.IGNORECASE,
)


def materialize_bbox_images(markdown, page_image):
    """
    Replace bbox references produced by OvisOCR2
    with embedded base64 JPEG crops.
    """

    if not markdown:
        return markdown

    width, height = page_image.size

    def replace(match):

        left, top, right, bottom = (
            int(x) for x in match.groups()
        )

        x1 = max(
            0,
            min(
                width,
                round(left * width / 1000),
            ),
        )

        y1 = max(
            0,
            min(
                height,
                round(top * height / 1000),
            ),
        )

        x2 = max(
            0,
            min(
                width,
                round(right * width / 1000),
            ),
        )

        y2 = max(
            0,
            min(
                height,
                round(bottom * height / 1000),
            ),
        )

        if x2 <= x1 or y2 <= y1:
            return match.group(0)

        crop = page_image.crop(
            (x1, y1, x2, y2)
        ).convert("RGB")

        crop.thumbnail(
            (1200, 1200),
            Image.Resampling.BILINEAR,
        )

        buffer = io.BytesIO()

        crop.save(
            buffer,
            format="JPEG",
            quality=85,
        )

        encoded = base64.b64encode(
            buffer.getvalue()
        ).decode("ascii")

        return (
            '<img '
            f'src="data:image/jpeg;base64,{encoded}" '
            'alt="Visual region" '
            'style="max-width:100%;height:auto;" />'
        )

    return BBOX_PATTERN.sub(
        replace,
        markdown,
    )


