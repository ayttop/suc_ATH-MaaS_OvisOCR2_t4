def ocr_pdf(file_obj, start_page, page_count):

    if file_obj is None:
        return "", "ارفع PDF أولًا."

    start_time = time.time()

    try:

        path = get_file_path(file_obj)

        document_type, total_pages = document_info(path)

        if document_type != "pdf":
            return "", "الملف ليس PDF."

        start_page = int(start_page) - 1
        page_count = int(page_count)

        if start_page < 0:
            start_page = 0

        if start_page >= total_pages:
            return (
                "",
                f"الصفحة المطلوبة غير موجودة. "
                f"الملف يحتوي على {total_pages} صفحات.",
            )

        end_page = min(
            total_pages,
            start_page + page_count,
        )

        all_pages = []

        print(
            f"[PDF] Processing pages "
            f"{start_page + 1}-{end_page}/{total_pages}",
            flush=True,
        )

        for page_index in range(
            start_page,
            end_page,
        ):

            page_number = page_index + 1

            print(
                f"[OCR] Page {page_number}/{end_page}",
                flush=True,
            )

            image = load_page(
                path,
                "pdf",
                page_index,
            )

            final_text = ""

            for partial in run_ocr_stream(image):
                final_text = partial

            rendered = materialize_bbox_images(
                final_text,
                image,
            )

            all_pages.append(
                f"<!-- Page {page_number} -->\n\n"
                f"{rendered}"
            )

            # تنظيف الذاكرة بعد كل صفحة
            del image

            if torch.cuda.is_available():
                torch.cuda.empty_cache()

        result = "\n\n---\n\n".join(
            all_pages
        )

        elapsed = time.time() - start_time

        status = (
            f"تم الانتهاء.\n"
            f"الصفحات: {start_page + 1}-{end_page}\n"
            f"إجمالي الصفحات في PDF: {total_pages}\n"
            f"الوقت: {elapsed:.1f} ثانية\n"
            f"عدد الأحرف: {len(result):,}"
        )

        return result, status

    except Exception as e:

        return (
            "",
            f"ERROR: {type(e).__name__}: {e}",
        )


