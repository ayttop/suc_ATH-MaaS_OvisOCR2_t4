def run_ocr_stream(image):
    """
    Run OCR and stream text progressively.
    """

    inputs = create_inputs(image)

    streamer = TextIteratorStreamer(
        processor.tokenizer,
        skip_prompt=True,
        skip_special_tokens=True,
        clean_up_tokenization_spaces=False,
    )

    errors = []

    def generate():

        try:

            with torch.inference_mode():

                model.generate(
                    **inputs,
                    streamer=streamer,
                    max_new_tokens=MAX_NEW_TOKENS,
                    do_sample=False,
                    temperature=None,
                    top_p=None,
                    top_k=None,
                    **generation_token_ids(),
                )

        except Exception as e:

            errors.append(e)

            try:
                streamer.on_finalized_text(
                    "",
                    stream_end=True,
                )
            except Exception:
                pass

    worker = threading.Thread(
        target=generate,
        daemon=True,
    )

    worker.start()

    text = ""

    for fragment in streamer:

        text += fragment

        yield text

    worker.join()

    if errors:
        raise RuntimeError(
            f"فشل تشغيل OvisOCR2: {errors[0]}"
        )

    return text


