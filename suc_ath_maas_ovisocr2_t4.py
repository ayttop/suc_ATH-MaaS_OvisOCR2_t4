def get_file_path(file_obj):
    """
    Get actual uploaded file path from Gradio.
    Supports both string paths and Gradio file objects.
    """

    if file_obj is None:
        raise ValueError("لم يتم رفع أي ملف.")

    if isinstance(file_obj, str):
        return file_obj

    if isinstance(file_obj, dict):
        path = file_obj.get("path")
        if path:
            return str(path)

    path = getattr(file_obj, "path", None)

    if path:
        return str(path)

    raise ValueError("تعذر الحصول على مسار الملف المرفوع.")


def document_info(path):
    """
    Detect whether uploaded file is an image or PDF.
    """

    path = str(path)
    suffix = Path(path).suffix.lower()

    # Check PDF header
    try:
        with open(path, "rb") as f:
            header = f.read(5)
    except Exception as e:
        raise ValueError("تعذر قراءة الملف.") from e

    if suffix == ".pdf" or header == b"%PDF-":

        with fitz.open(path) as doc:
            total_pages = doc.page_count

        if total_pages < 1:
            raise ValueError("ملف PDF لا يحتوي على صفحات.")

        if total_pages > MAX_PDF_PAGES:
            raise ValueError(
                f"الحد الأقصى هو {MAX_PDF_PAGES} صفحة. "
                f"الملف يحتوي على {total_pages} صفحة."
            )

        return "pdf", total_pages

    # Validate image
    try:
        with Image.open(path) as img:
            img.verify()
    except Exception as e:
        raise ValueError(
            "الملف يجب أن يكون PNG أو JPEG أو WebP أو PDF."
        ) from e

    return "image", 1


def load_page(path, document_type, page_index):
    """
    Load one page as PIL RGB image.
    """

    if document_type == "pdf":

        with fitz.open(path) as doc:

            page = doc.load_page(page_index)

            pix = page.get_pixmap(
                matrix=fitz.Matrix(
                    PDF_RENDER_SCALE,
                    PDF_RENDER_SCALE,
                ),
                colorspace=fitz.csRGB,
                alpha=False,
            )

            return Image.frombytes(
                "RGB",
                (pix.width, pix.height),
                pix.samples,
            )

    with Image.open(path) as img:
        return ImageOps.exif_transpose(img).convert("RGB")


