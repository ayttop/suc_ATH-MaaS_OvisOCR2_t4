    start = time.time()

    try:

        path = get_file_path(file_obj)

        document_type, total_pages = document_info(path)

        if document_type != "image":
            return "", "هذا زر الصور فقط. استخدم زر PDF."

        image = load_page(
            path,
            "image",
            0,
        )

        print(
            f"[OCR] Image size: {image.size}",
            flush=True,
        )

        final_text = ""

        for partial in run_ocr_stream(image):

            final_text = partial

            # Gradio يحتاج return في نهاية الوظيفة،
            # لذلك لا نستخدم yield هنا.
            # يتم تحديث النتيجة بعد انتهاء التوليد.

        rendered = materialize_bbox_images(
            final_text,
            image,
        )

        elapsed = time.time() - start

        status = (
            f"تم الانتهاء.\n"
            f"الوقت: {elapsed:.1f} ثانية\n"
            f"عدد الأحرف: {len(final_text):,}"
        )

        return rendered, status

    except Exception as e:

        return (
            "",
            f"ERROR: {type(e).__name__}: {e}",
        )


